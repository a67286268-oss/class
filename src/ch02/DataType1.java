package ch02;

/**
 * 데이터 타입이란?
 * 변수라는 상자에 담을 수 있는 값의 종류와 크기를 지정하는 것
 * 상자의 크기에 따라서 담을 수 있는 값의 범위가 달라짐
 *
 * 자바에서는 데이터 타입을 가장 큰 분류로 2가지로 구분한다
 * 1. 기본 자료형(Primitive Data Type)
 *      > 정수형, 문자형, 실수형, 논리형
 * 2. 참조 자료형(Reference Data Type)
 */
public class DataType1 {
    // 메인함수 (코트실행의 시작 점)
    public static void main(String[] args) {

        // 정수형 - 정수는 소수점 이하를 포함하지 않는 숫자를 의미
        byte byteBox; // 1바이트
        short shortBox; // 2바이트
        int intBox; // 4바이트 (정수형 데이터 타입의 기본형)
        long longBox; // 8바이트

        // 데이터는 2진수로 표현 0과1

        // 10진수란? 0~9 까지

    } // end of main
} // end of class
