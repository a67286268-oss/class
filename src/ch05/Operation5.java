package ch05;

public class Operation5 {

    public static void main(String[] args) {

        int n1 = 5;
        int n2 = 3;

        boolean result1 = n1 > n2; // true
        System.out.println(n1 > n2); // true n1이 n2보다 크다
        System.out.println(n1 < n2); // false n1이 n2보다 작다
        System.out.println(n1 >= n2); // true n1이 n2보다 크거나같다
        System.out.println(n1 <= n2); // false n1이 n2보다 작거나같다
        System.out.println(n1 == n2); // false n1와 n2가 같다
        System.out.println(n1 != n2); // true n1와 n2가 같지않다

    }

}
